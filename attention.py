# Розгляньмо переклад **The cat sat on the mat. → Кіт сидів на килимку.**
# Англійське речення вже відоме повністю. На кожному кроці decoder створює
# новий запит із поточного українського префікса. Через **cross-attention**
# він отримує зважену суміш інформації з англійських токенів.
#
# ![Heatmap cross-attention до токенів англійського речення](figures/source_attention.svg)
#
# **Як читати heatmap:** стовпець — токен джерела; рядок — один крок
# перекладу. Ліворуч зазначено префікс, із якого отримано запит, праворуч —
# наступний токен для орієнтації. Темніша клітинка означає більшу вагу.
# Сума ваг у кожному рядку дорівнює 1.
#
