# %% [markdown]
#
# ## Softmax: оцінки перетворюються на ваги
#
# Для оцінок $s_1,\ldots,s_n$ softmax повертає
# $p_i=e^{s_i}/\sum_j e^{s_j}$. Математично кожна вага додатна, а сума
# ваг дорівнює 1; у Python можливі похибки округлення.
# Softmax діє на **весь вектор**, на відміну від поелементних ReLU і GELU.
# У багатокласовій класифікації модель спочатку видає довільні оцінки
# (логіти) для кожного класу. Softmax перетворює їх на розподіл: числа від 0
# до 1, сума яких дорівнює 1 з точністю до округлення. Тому їх часто
# інтерпретують як імовірності класів. Проте сама нормалізація не гарантує,
# що модель добре відкалібрована: вага 0.9 не обов'язково означає 90% успіху
# на реальних даних. В attention ці самі числа — частки внеску значень, а не
# ймовірності того, що певний ключ є «правильною відповіддю».
#
# Наприклад, для оцінок класів `[0, ln(3)]` маємо ваги `[0.25, 0.75]`.
# Другий клас отримує втричі більшу вагу, хоча різниця логітів — лише `ln(3)`.
#
# На `figures/softmax.svg` показано, як зміна однієї оцінки змінює всі ваги.
# Спробуйте вручну обчислити softmax для `[0, 0]` та `[0, ln(3)]`.
#
# ![Ваги softmax для двох елементів з підписами осей і легендою](figures/softmax.svg)
#
# Простежмо обчислення для `[0, ln(3)]`: експоненти — `[1, 3]`, їхня
# сума — 4, після ділення маємо `[1/4, 3/4]`. Збільшення однієї оцінки
# змінює знаменник, тому змінюються ваги **обох** елементів.

# %%
from math import exp, log

example_scores = [0, log(3)]
example_exps = [exp(score) for score in example_scores]
example_total = sum(example_exps)
print("Оцінки:", example_scores)
print("Експоненти:", example_exps)
print("Сума експонент:", example_total)
print("Ваги:", [value / example_total for value in example_exps])

# %% [markdown]
#
# ### Чому пряме обчислення переповнюється?
#
# `exp` дуже швидко зростає: $e^{10}$ — близько 22 тисяч, $e^{100}$ —
# близько $2.69\cdot10^{43}$. У звичайного Python `float` найбільше
# скінченне значення приблизно $1.80\cdot10^{308}$. Уже $e^{710}$ більше
# за цю межу. У Python `math.exp` тоді піднімає `OverflowError`.
#
# Запустіть комірку: softmax для `[1000, 1001]` не доходить навіть до
# ділення — помилка виникає під час обчислення першої експоненти.
# Обробка помилки тут дозволяє продовжити виконання ноутбука.

# %%
from math import exp
from sys import float_info

print("Найбільший скінченний float:", float_info.max)
for score in [10, 100, 700, 709, 710, 1000]:
    try:
        print(f"exp({score}) = {exp(score):.3e}")
    except OverflowError:
        print(f"exp({score}): OverflowError — результат не вміщується у float")

large_scores = [1000, 1001]
try:
    large_exps = [exp(score) for score in large_scores]
    print([value / sum(large_exps) for value in large_exps])
except OverflowError:
    print("Прямий softmax([1000, 1001]) зупинився на обчисленні exp(1000).")

# %% [markdown]
#
# Але прямий виклик `exp(1000)` переповнює числа з плаваючою комою. Віднімання
# одного й того самого числа від усіх оцінок не змінює softmax:
#
# $$\frac{e^{s_i-c}}{\sum_j e^{s_j-c}}=
# \frac{e^{s_i}}{\sum_j e^{s_j}}.$$
#
# Оберіть $c=\max(s)$. Тоді найбільший показник експоненти дорівнює нулю,
# а решта — від'ємні. Порожній вектор вважайте помилкою `ValueError`.
# Припускаємо, що оцінки — скінченні числа.
#
# Для `[1000, 1001]` віднімаємо 1001: отримуємо `[-1, 0]`.
# Тепер експоненти приблизно `[0.368, 1]`, а ваги — `[0.269, 0.731]`.
# Великі початкові оцінки не заважають: важливі їхні **різниці**.
# Дуже від'ємний аргумент може дати експоненту 0 через округлення
# (underflow). Але після віднімання максимуму принаймні одна експонента
# дорівнює 1, тому знаменник не буде нульовим.

# %%
shifted_scores = [score - max(large_scores) for score in large_scores]
safe_exps = [exp(score) for score in shifted_scores]
safe_weights = [value / sum(safe_exps) for value in safe_exps]
print("Після віднімання максимуму:", shifted_scores)
print("Експоненти:", safe_exps)
print("Ваги:", safe_weights)

