# ## Увага для одного запиту
#
# Увага дає одному вектору змогу зібрати інформацію з інших позицій.
# `query` описує, що шукаємо; кожен `key` описує, за яким запитом доступна
# інформація; парний `value` містить саму інформацію для перенесення.
# Запит порівнюємо з кожним ключем через скалярний добуток з першої
# лабораторної. Великий добуток означає, що вектори спрямовані схоже.
# Softmax перетворює ці оцінки на ваги, а зважена сума значень формує новий
# вектор. Модель навчає проєкції, які створюють Q, K і V з вхідних векторів;
# тому подібність тут набуває змісту під час навчання, а не задана наперед.
#
# $$s_i=\frac{q\cdot k_i}{\sqrt{d_k}},\qquad
# \alpha=\operatorname{softmax}(s),\qquad
# o=\sum_i\alpha_i v_i.$$
#
# Розгляньмо `query = [1, 0]` і три ключі `[1, 0]`, `[0, 1]`, `[-1, 0]`.
# Їхні скалярні добутки із запитом: `[1, 0, -1]`. Після ділення на
# $\sqrt{2}$ та softmax ваги приблизно `[0.576, 0.284, 0.140]`.
# Перший ключ узгоджується із запитом найбільше, але інші не зникають:
